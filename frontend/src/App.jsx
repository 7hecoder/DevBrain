  const [jwtToken, setJwtToken] = useState("");


  const selectedTool = tools.find((tool) => tool.id === activeTool) || tools[0];
  const SelectedIcon = selectedTool.icon;

  function selectTool(id) {
    setActiveTool(id);
    setResult(null);
    setError("");
    setCopied(false);
    setMobileMenuOpen(false);
  }

  async function copyToClipboard(value) {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      setError("Clipboard access failed. Select and copy the result manually.");
    }
  }

  async function runTool(event) {
    event.preventDefault();
    setLoading(true);
    setError("");
    setResult(null);
    setCopied(false);

    try {
      let data;

      switch (activeTool) {
        case "password": {
          const length = Number(passwordLength);
          if (!Number.isInteger(length) || length < 8 || length > 128) {
            throw new Error("Enter a password length between 8 and 128.");
          }
          data = await apiRequest(`/password?length=${length}`);
          break;
        }


        case "hash": {
          if (!text.trim()) throw new Error("Enter text to hash.");

          data = await apiRequest("/hash", {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
            },
            body: JSON.stringify({
              algorithm,
              text,
            }),
          });
          break;
        }


        case "uuid": {
          data = await apiRequest("/uuid");
          break;
        }

        case "timestamp": {
          if (timestamp.trim() === "" || !Number.isFinite(Number(timestamp))) {
            throw new Error("Enter a valid numeric Unix timestamp.");
          }
          data = await apiRequest(`/timestamp/${encodeURIComponent(timestamp.trim())}`);
          if (data?.error) throw new Error(data.error);
          break;
        }


        case "base64": {
          if (!base64Text) throw new Error("Enter text first.");

          data = await apiRequest(`/base64/${base64Mode}`, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
            },
            body: JSON.stringify({ text: base64Text }),
          });
          break;
        }



        case "json": {
          data = await apiRequest("/json/format", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ text: jsonText }),
          });
          break;
        }

        case "url": {
          if (!urlText) throw new Error("Enter text first.");

          data = await apiRequest(`/url/${urlMode}`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ text: urlText }),
          });
          break;
        }

        case "diff": {
          data = await apiRequest("/diff", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              original: diffOriginal,
              modified: diffModified,
            }),
          });
          break;
        }

        case "regex": {
          if (!regexPattern) {
            throw new Error("Enter a regular expression.");
          }

          data = await apiRequest("/regex", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              pattern: regexPattern,
              text: regexText,
              flags: regexFlags,
            }),
          });
          break;
        }

        case "jwt": {
          if (!jwtToken.trim()) {
            throw new Error("Paste a JWT first.");
          }

          data = await apiRequest("/jwt/decode", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ token: jwtToken.trim() }),
          });
          break;
        }


        default:
          throw new Error("Select a valid tool.");
      }

      setResult(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Something went wrong.");
    } finally {
      setLoading(false);
    }
  }

