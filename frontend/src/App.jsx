async function apiRequest(path, options = {}) {
  const response = await fetch(`${import.meta.env.VITE_API_BASE_URL || "/api"}${path}`, options);
  const contentType = response.headers.get("content-type") || "";

  let data;
  if (contentType.includes("application/json")) {
    data = await response.json();
  } else {
    data = await response.text();
  }

  if (!response.ok) {
    const message =
      typeof data === "object" && data !== null
        ? data.detail || data.error || "The request failed."
        : String(data || "The request failed.");

    throw new Error(message);
  }

  return data;
}


function ResultPanel({ result, onCopy, copied }) {
  if (result === null || result === undefined) return null;

  const isObject = typeof result === "object" && result !== null;

  const formattedResult = isObject
    ? JSON.stringify(result, null, 2)
    : String(result);

  const entries = isObject ? Object.entries(result) : [];

  const displayValue = (value) => {
    if (value === null) return "null";

    if (typeof value === "object") {
      return JSON.stringify(value, null, 2);
    }

    return String(value);
  };

  const isError =
    isObject &&
    (Boolean(result.detail) ||
      Boolean(result.error));

  return (
    <section className="mt-6 overflow-hidden rounded-2xl border border-slate-800 bg-slate-950/70">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-800 px-5 py-4">
        <div>
          <p className="text-sm font-semibold text-white">
            {isError ? "Request Error" : "Result"}
          </p>
          <p className="mt-1 text-xs text-slate-500">
            {isError
              ? "The API returned an error"
              : "Generated by the DevBrain API"}
          </p>
        </div>

        <button
          type="button"
          onClick={() => onCopy(formattedResult)}
          className="inline-flex items-center gap-2 rounded-lg border border-slate-700 px-3 py-2 text-xs font-medium text-slate-300 transition hover:border-cyan-500 hover:text-white"
        >
          {copied ? <Check size={14} /> : <Copy size={14} />}
          {copied ? "Copied" : "Copy result"}
        </button>
      </div>

      {isObject ? (
        <div className="space-y-0 px-5 py-2">
          {entries.map(([key, value]) => (
            <div
              key={key}
              className="grid gap-2 border-b border-slate-800/70 py-4 last:border-0 sm:grid-cols-[140px_minmax(0,1fr)]"
            >
              <span className="break-words text-xs font-medium capitalize text-slate-500">
                {key.replaceAll("_", " ")}
              </span>

              <pre
                className={`overflow-x-auto whitespace-pre-wrap break-words rounded-lg p-3 font-mono text-sm leading-6 ${isError
                  ? "bg-red-950/30 text-red-300"
                  : "bg-slate-900/70 text-emerald-300"
                  }`}
              >
                {displayValue(value)}
              </pre>
            </div>
          ))}
        </div>
      ) : (
        <pre className="max-h-[500px] overflow-auto whitespace-pre-wrap break-words p-5 font-mono text-sm leading-6 text-emerald-300">
          {formattedResult}
        </pre>
      )}
    </section>
  );
}


